/** @param {import('./routes.mjs').Locale} locale @param {keyof typeof FORMATS.en} key @param {Record<string, string | number>} [values] */
export function formatMessage(locale, key, values = {}) {
  return FORMATS[locale][key].replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}

/** Keep the PDF safety checks unchanged; translate their errors at the UI boundary. */
export function localizedError(error, fallback, locale) {
  const t = TRANSLATORS[locale];
  if (!(error instanceof Error) || !error.message) return t(fallback);
  const image = error.message.match(/^Pagina (\d+): immagine non decodificata\. Il PDF precedente è stato conservato\.$/);
  if (image) return formatMessage(locale, 'imageError', { page: image[1] });
  if (/WinAnsi cannot encode/.test(error.message)) return locale === 'en'
    ? 'The selected font cannot display one or more characters. Change the text or use a tool that supports those characters. Your previous PDF has been kept.'
    : 'Il font selezionato non supporta uno o più caratteri. Modifica il testo o usa uno strumento che li supporti. Il PDF precedente è stato conservato.';
  return t(error.message);
}
